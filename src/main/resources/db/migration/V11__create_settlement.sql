-- 결제자 계좌는 참여자가 처음 정산 건의 결제자가 될 때 한 번만 넣고 바꾸지 않는다(#124).
-- participant 행을 다시 쓰지 않도록 별도 테이블에 두고, 은행 이름과 계좌번호는 모임별 데이터 키로 암호화한 값만 저장한다.
CREATE TABLE participant_bank_account (
    participant_id           BIGINT       NOT NULL,
    encrypted_bank_name      BYTEA        NOT NULL,
    encrypted_account_number BYTEA        NOT NULL,
    consent_version          VARCHAR(20)  NOT NULL,
    consented_at             TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_participant_bank_account PRIMARY KEY (participant_id),
    CONSTRAINT fk_participant_bank_account_participant FOREIGN KEY (participant_id) REFERENCES participant (id)
);

-- 정산 건 하나는 카드 결제 1건이다. notified_at은 정산 메시지를 보낼 때 채운다(#126).
-- version은 수정, 취소, 발송, 입금 상태 전이가 동시에 들어올 때 나중 요청을 막는 낙관적 락이다.
-- 인원 기본값을 찾을 때 모임으로, 파기할 때 결제자로 조회하므로(#128) 두 FK 컬럼에 인덱스를 둔다.
CREATE TABLE settlement (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    gathering_id         BIGINT       NOT NULL,
    payer_participant_id BIGINT       NOT NULL,
    total_amount         BIGINT       NOT NULL CHECK (total_amount > 0),
    recorded_at          TIMESTAMP(6) NOT NULL,
    notified_at          TIMESTAMP(6),
    cancelled_at         TIMESTAMP(6),
    version              BIGINT       NOT NULL,
    created_at           TIMESTAMP(6),
    updated_at           TIMESTAMP(6),
    CONSTRAINT pk_settlement PRIMARY KEY (id),
    CONSTRAINT fk_settlement_gathering FOREIGN KEY (gathering_id) REFERENCES gathering (id),
    CONSTRAINT fk_settlement_payer_participant FOREIGN KEY (payer_participant_id) REFERENCES participant (id)
);

CREATE INDEX idx_settlement_gathering_id ON settlement (gathering_id);
CREATE INDEX idx_settlement_payer_participant_id ON settlement (payer_participant_id);

-- 결제자를 뺀 참여자의 분담이다. 결제자 분담액은 총액에서 이 행들의 금액 합을 빼서 구한다.
-- unique 제약의 선두 컬럼이 settlement_id라서 settlement FK 조회용 인덱스를 따로 두지 않는다.
CREATE TABLE settlement_share (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    settlement_id  BIGINT       NOT NULL,
    participant_id BIGINT       NOT NULL,
    amount         BIGINT       NOT NULL CHECK (amount >= 0),
    fixed          BOOLEAN      NOT NULL,
    payment_status VARCHAR(255) NOT NULL CHECK (payment_status IN ('UNPAID', 'SENT', 'CONFIRMED')),
    CONSTRAINT pk_settlement_share PRIMARY KEY (id),
    CONSTRAINT fk_settlement_share_settlement FOREIGN KEY (settlement_id) REFERENCES settlement (id),
    CONSTRAINT fk_settlement_share_participant FOREIGN KEY (participant_id) REFERENCES participant (id),
    CONSTRAINT uk_settlement_share_participant UNIQUE (settlement_id, participant_id)
);

CREATE INDEX idx_settlement_share_participant_id ON settlement_share (participant_id);
