-- 관계 유형과 분위기별 조합 평점 집계다(#176). 조합별 전역 집계 pairing_rating_summary는 그대로 둔다.
-- 분위기는 선택 입력이라 NULL도 하나의 상황으로 센다. 기본 키는 NULL을 담지 못하므로 대리키를 두고 UNIQUE NULLS NOT DISTINCT로 상황마다 한 행만 허용한다.
-- 추천은 요청한 상황의 집계를 읽으므로 상황 컬럼을 앞에 둔 유니크 인덱스를 조회에도 쓴다.
-- 카탈로그를 지울 때는 pairing_feedback이 먼저 막으므로 FK 컬럼은 따로 인덱싱하지 않는다.
CREATE TABLE pairing_situation_rating_summary (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    relationship_type VARCHAR(255) NOT NULL,
    mood_type         VARCHAR(255),
    drink_id          BIGINT       NOT NULL,
    anju_id           BIGINT       NOT NULL,
    like_count        INTEGER      NOT NULL CHECK (like_count >= 0),
    dislike_count     INTEGER      NOT NULL CHECK (dislike_count >= 0),
    CONSTRAINT pk_pairing_situation_rating_summary PRIMARY KEY (id),
    CONSTRAINT uk_pairing_situation_rating_summary UNIQUE NULLS NOT DISTINCT (relationship_type, mood_type, drink_id, anju_id),
    CONSTRAINT ck_pairing_situation_rating_summary_relationship_type CHECK (relationship_type IN ('BOSS', 'FRIEND', 'COLLEAGUE', 'LOVER')),
    CONSTRAINT ck_pairing_situation_rating_summary_mood_type CHECK (mood_type IN ('FORMAL', 'CASUAL', 'ROMANTIC', 'CELEBRATORY')),
    CONSTRAINT fk_pairing_situation_rating_summary_drink FOREIGN KEY (drink_id) REFERENCES drink (id),
    CONSTRAINT fk_pairing_situation_rating_summary_anju FOREIGN KEY (anju_id) REFERENCES anju (id)
);

-- 기존 피드백을 상황별로 다시 센다. 익명 피드백도 관계 유형과 분위기를 가지므로 함께 센다.
INSERT INTO pairing_situation_rating_summary (relationship_type, mood_type, drink_id, anju_id, like_count, dislike_count)
SELECT relationship_type,
       mood_type,
       drink_id,
       anju_id,
       COUNT(*) FILTER (WHERE rating = 'LIKE'),
       COUNT(*) FILTER (WHERE rating = 'DISLIKE')
FROM pairing_feedback
GROUP BY relationship_type, mood_type, drink_id, anju_id;
