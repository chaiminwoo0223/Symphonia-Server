-- 모임과 참여자를 담는다(#123). host_member_id는 member 도메인을 가리키는 도메인 간 참조라 FK를 걸지 않는다.
CREATE TABLE gathering (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    host_member_id BIGINT       NOT NULL,
    name           VARCHAR(255) NOT NULL,
    created_at     TIMESTAMP(6),
    updated_at     TIMESTAMP(6),
    CONSTRAINT pk_gathering PRIMARY KEY (id)
);

-- 모임별 데이터 키는 마스터 키로 감싼 값만 저장한다. 파기할 때 이 행을 먼저 지워 남은 암호문을 풀 수 없게 한다(#128).
CREATE TABLE gathering_data_key (
    gathering_id         BIGINT NOT NULL,
    encrypted_cipher_key BYTEA  NOT NULL,
    encrypted_hmac_key   BYTEA  NOT NULL,
    CONSTRAINT pk_gathering_data_key PRIMARY KEY (gathering_id),
    CONSTRAINT fk_gathering_data_key_gathering FOREIGN KEY (gathering_id) REFERENCES gathering (id)
);

-- 토큰은 원본 대신 SHA-256 해시(hex 64자)만 저장하고, 해시로 모임과 참여자를 찾으므로 unique 제약이 조회 인덱스를 겸한다.
-- 모임마다 참여 토큰은 하나라서 gathering_id를 기본 키로 두고, 재발급하면 이 행의 해시를 덮어쓴다.
CREATE TABLE gathering_join_token (
    gathering_id BIGINT      NOT NULL,
    token_hash   VARCHAR(64) NOT NULL,
    CONSTRAINT pk_gathering_join_token PRIMARY KEY (gathering_id),
    CONSTRAINT fk_gathering_join_token_gathering FOREIGN KEY (gathering_id) REFERENCES gathering (id),
    CONSTRAINT uk_gathering_join_token_hash UNIQUE (token_hash)
);

-- 이름과 휴대폰은 모임별 데이터 키로 암호화한 값만 저장한다.
-- 같은 모임에 같은 휴대폰으로 동시에 참여하는 경우를 phone_number_hmac unique 제약으로 막는다.
-- 이 제약의 선두 컬럼이 gathering_id라서 FK 조회용 인덱스를 따로 두지 않는다.
CREATE TABLE participant (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    gathering_id           BIGINT       NOT NULL,
    encrypted_name         BYTEA        NOT NULL,
    encrypted_phone_number BYTEA        NOT NULL,
    phone_number_hmac      VARCHAR(64)  NOT NULL,
    non_drinker            BOOLEAN      NOT NULL,
    consent_version        VARCHAR(20)  NOT NULL,
    consented_at           TIMESTAMP(6) NOT NULL,
    created_at             TIMESTAMP(6),
    updated_at             TIMESTAMP(6),
    CONSTRAINT pk_participant PRIMARY KEY (id),
    CONSTRAINT fk_participant_gathering FOREIGN KEY (gathering_id) REFERENCES gathering (id),
    CONSTRAINT uk_participant_phone_number UNIQUE (gathering_id, phone_number_hmac)
);

-- 정산 메시지를 보낼 때마다 새 토큰을 더 발급하고(#126) 앞서 받은 링크도 계속 쓰게 하므로, 참여자마다 토큰을 여러 개 둔다.
-- 파기할 때 참여자의 토큰을 participant_id로 지우므로(#128) FK 컬럼에 인덱스를 둔다.
CREATE TABLE participant_link_token (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    participant_id BIGINT      NOT NULL,
    token_hash     VARCHAR(64) NOT NULL,
    CONSTRAINT pk_participant_link_token PRIMARY KEY (id),
    CONSTRAINT fk_participant_link_token_participant FOREIGN KEY (participant_id) REFERENCES participant (id),
    CONSTRAINT uk_participant_link_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_participant_link_token_participant_id ON participant_link_token (participant_id);
