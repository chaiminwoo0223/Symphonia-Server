-- 모임장이 고른 조합의 선택 횟수를 상황별로 센다(#211). 모임 페어링은 모임을 파기할 때 함께 지워져 선택 신호가 남지 않았다.
-- 개인정보 없이 횟수만 두고, 모임이나 회원을 가리키는 값은 담지 않는다.
-- 분위기는 선택 입력이라 NULL도 하나의 상황으로 센다. 기본 키는 NULL을 담지 못하므로 대리키를 두고 UNIQUE NULLS NOT DISTINCT로 상황마다 한 행만 허용한다.
-- 개인정보 파기가 이 집계 때문에 실패하면 안 되므로 drink, anju에 FK를 걸지 않는다. 모임 페어링이 가리킨 대상이 카탈로그에서 사라졌어도 파기는 끝나야 한다.
CREATE TABLE pairing_selection_summary (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    relationship_type VARCHAR(255) NOT NULL,
    mood_type         VARCHAR(255),
    drink_id          BIGINT       NOT NULL,
    anju_id           BIGINT       NOT NULL,
    selection_count   INTEGER      NOT NULL CHECK (selection_count > 0),
    CONSTRAINT pk_pairing_selection_summary PRIMARY KEY (id),
    CONSTRAINT uk_pairing_selection_summary UNIQUE NULLS NOT DISTINCT (relationship_type, mood_type, drink_id, anju_id),
    CONSTRAINT ck_pairing_selection_summary_relationship_type CHECK (relationship_type IN ('BOSS', 'FRIEND', 'COLLEAGUE', 'LOVER')),
    CONSTRAINT ck_pairing_selection_summary_mood_type CHECK (mood_type IN ('FORMAL', 'CASUAL', 'ROMANTIC', 'CELEBRATORY'))
);
