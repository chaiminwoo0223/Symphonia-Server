CREATE TABLE drink_style (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(255) NOT NULL,
    category    VARCHAR(255) NOT NULL,
    sweetness   INTEGER      NOT NULL,
    bitterness  INTEGER      NOT NULL,
    carbonation INTEGER      NOT NULL,
    richness    INTEGER      NOT NULL,
    acidity     INTEGER      NOT NULL,
    CONSTRAINT pk_drink_style PRIMARY KEY (id),
    -- 값이 늘어날 때 후속 마이그레이션이 DROP 후 다시 ADD할 수 있도록 check 제약에 이름을 붙인다.
    CONSTRAINT ck_drink_style_category CHECK (category IN (
        'BEER', 'WINE', 'SOJU', 'MAKGEOLLI', 'WHISKY', 'HIGHBALL', 'NON_ALCOHOLIC')),
    CONSTRAINT uk_drink_style_name UNIQUE (name)
);

