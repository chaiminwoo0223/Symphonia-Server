    (8, 8, 'non-alcoholic-highball')
) AS seed (drink_id, drink_style_id, external_id)
WHERE drink.id = seed.drink_id;

ALTER TABLE drink
    ALTER COLUMN drink_style_id SET NOT NULL,
    ALTER COLUMN source SET NOT NULL,
    ALTER COLUMN external_id SET NOT NULL,
    ADD CONSTRAINT ck_drink_source CHECK (source IN ('SEED')),
    ADD CONSTRAINT fk_drink_drink_style FOREIGN KEY (drink_style_id) REFERENCES drink_style (id),
    ADD CONSTRAINT uk_drink_source_external_id UNIQUE (source, external_id);
