-- 기존 행을 채운 뒤에 NOT NULL을 걸어야 행이 있는 DB에서도 컬럼 추가가 실패하지 않는다.
ALTER TABLE drink
    ADD COLUMN drink_style_id BIGINT,
    ADD COLUMN source         VARCHAR(255),
    ADD COLUMN external_id    VARCHAR(255);

UPDATE drink
SET drink_style_id = seed.drink_style_id,
    source         = 'SEED',
    external_id    = seed.external_id
FROM (VALUES
    (1, 1, 'soju'),
    (2, 2, 'beer'),
    (3, 3, 'makgeolli'),
    (4, 4, 'red-wine'),
    (5, 5, 'whisky'),
