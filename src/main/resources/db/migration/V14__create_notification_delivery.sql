-- 참여자 한 명에게 보내는 메시지 한 건의 발송 기록이다(#126). 큐에는 이 행의 id만 발행한다.
-- 발행에 실패했거나 메시지를 잃어도, PENDING으로 남은 행을 폴러가 다시 발행해 복구한다.
-- 모임을 파기할 때 모임과 참여자로 지우므로(#128) 두 FK 컬럼에 인덱스를 둔다.
CREATE TABLE notification_delivery (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    gathering_id   BIGINT       NOT NULL,
    participant_id BIGINT       NOT NULL,
    type           VARCHAR(20)  NOT NULL CHECK (type IN ('SETTLEMENT', 'CANCELLATION')),
    status         VARCHAR(20)  NOT NULL CHECK (status IN ('PENDING', 'SENT', 'SKIPPED', 'FAILED')),
    attempts       INTEGER      NOT NULL CHECK (attempts >= 0),
    available_at   TIMESTAMP(6) NOT NULL,
    published_at   TIMESTAMP(6),
    claimed_at     TIMESTAMP(6),
    sent_at        TIMESTAMP(6),
    created_at     TIMESTAMP(6),
    updated_at     TIMESTAMP(6),
    CONSTRAINT pk_notification_delivery PRIMARY KEY (id),
    CONSTRAINT fk_notification_delivery_gathering FOREIGN KEY (gathering_id) REFERENCES gathering (id),
    CONSTRAINT fk_notification_delivery_participant FOREIGN KEY (participant_id) REFERENCES participant (id)
);

CREATE INDEX idx_notification_delivery_gathering_id ON notification_delivery (gathering_id);
CREATE INDEX idx_notification_delivery_participant_id ON notification_delivery (participant_id);

-- 폴러가 짧은 주기로 발행할 발송 기록을 찾으므로, 아직 보내지 않은 행만 인덱스에 둔다.
CREATE INDEX idx_notification_delivery_pending ON notification_delivery (available_at)
    WHERE status = 'PENDING';

-- 메시지에 담을 정산 건이다. 발송 기록을 만들 때 한 번 넣고 바꾸지 않는다.
-- 취소 알림의 수신자를 정산 건으로 찾으므로 settlement_id에 인덱스를 둔다.
CREATE TABLE notification_delivery_settlement (
    delivery_id   BIGINT NOT NULL,
    settlement_id BIGINT NOT NULL,
    CONSTRAINT pk_notification_delivery_settlement PRIMARY KEY (delivery_id, settlement_id),
    CONSTRAINT fk_notification_delivery_settlement_delivery FOREIGN KEY (delivery_id) REFERENCES notification_delivery (id),
    CONSTRAINT fk_notification_delivery_settlement_settlement FOREIGN KEY (settlement_id) REFERENCES settlement (id)
);

CREATE INDEX idx_notification_delivery_settlement_settlement_id ON notification_delivery_settlement (settlement_id);
