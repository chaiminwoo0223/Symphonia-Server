-- 차수는 모임 안의 술자리 단위이고, 정산 건은 차수 하나에 속한다(#194).
-- 같은 번호를 동시에 추가해도 한 행만 생기도록 (gathering_id, round_number)에 unique 제약을 둔다. 이 제약의 선두 컬럼이 gathering_id라서 FK 조회용 인덱스를 따로 두지 않는다.
CREATE TABLE gathering_round (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    gathering_id BIGINT  NOT NULL,
    round_number INTEGER NOT NULL CHECK (round_number > 0),
    CONSTRAINT pk_gathering_round PRIMARY KEY (id),
    CONSTRAINT fk_gathering_round_gathering FOREIGN KEY (gathering_id) REFERENCES gathering (id),
    CONSTRAINT uk_gathering_round_number UNIQUE (gathering_id, round_number)
);

-- 모든 기존 모임에 1차를 만든다. 모임을 열 때 1차를 자동으로 만드는 규칙과 같게 하기 위해서다.
INSERT INTO gathering_round (gathering_id, round_number)
SELECT id, 1 FROM gathering;

-- 기존 정산 건에는 차수를 구분할 정보가 없어 모두 1차에 넣는다.
ALTER TABLE settlement ADD COLUMN round_id BIGINT;

UPDATE settlement
SET round_id = (
    SELECT gr.id FROM gathering_round gr
    WHERE gr.gathering_id = settlement.gathering_id AND gr.round_number = 1);

ALTER TABLE settlement ALTER COLUMN round_id SET NOT NULL;
ALTER TABLE settlement ADD CONSTRAINT fk_settlement_round FOREIGN KEY (round_id) REFERENCES gathering_round (id);

-- 파기할 때 정산 건을 지운 뒤 차수를 지우면 FK 검사가 settlement.round_id를 조회하므로 인덱스를 둔다.
CREATE INDEX idx_settlement_round_id ON settlement (round_id);
